// The cache key must change when the pipeline changes, without anyone having
// to remember it. A hand bumped "v3" sat unbumped through five prompt fixes,
// so students kept seeing matches the current prompts already reject, replayed
// from storage. The key is now a hash of every file whose content decides what
// a result looks like: change a prompt, the catalog, or the solver, and every
// cached result self-invalidates on the next visit.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, readdirSync } from "node:fs";

const DECIDES_RESULTS = [
  "app/api/fit/route.ts",
  "app/api/skills/route.ts",
  "app/api/summary/route.ts",
  "app/api/chat/route.ts",
  "lib/solver/core.ts",
  "lib/solver/index.ts",
  "data/columbia.ts",
  "data/columbia-extra.ts",
];

const h = createHash("sha256");
for (const f of DECIDES_RESULTS) h.update(readFileSync(f));
const version = h.digest("hex").slice(0, 12);

const out = `// Generated by scripts/gen-pipeline-version.mjs before every dev and build.
// Do not edit by hand: it is a content hash of the prompts, the solver and the
// catalog, and its whole job is to change when they do.
export const PIPELINE_VERSION = "${version}";
`;
writeFileSync("lib/pipeline-version.ts", out);
console.log("pipeline version:", version);
